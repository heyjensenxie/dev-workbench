export type MessageKey = keyof typeof messages['en-US']

/** Reads a preference without assuming a browser environment. */
function readStored(key: string): string | null {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage.getItem(key)
  } catch {
    return null
  }
}

function writeStored(key: string, value: string): void {
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(key, value)
  } catch {
    // Storage can be unavailable; preferences then only live for this session.
  }
}

function detectLocale(): Locale {
  const saved = readStored('locale')
  if (saved === 'zh-CN' || saved === 'en-US') return saved
  const language = typeof navigator === 'undefined' ? '' : navigator.language ?? ''
  return language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

const locale = ref<Locale>(detectLocale())
const languageLabel = computed(() => locale.value === 'zh-CN' ? 'EN' : '中')

function setLocale(next: Locale): void {
  locale.value = next
  writeStored('locale', next)
  if (typeof document !== 'undefined') document.documentElement.lang = next
}
function toggleLocale(): void {
  setLocale(locale.value === 'zh-CN' ? 'en-US' : 'zh-CN')
}
function t(key: MessageKey): string { return messages[locale.value][key] }

if (typeof document !== 'undefined') document.documentElement.lang = locale.value

export function useI18n() { return { locale, languageLabel, t, toggleLocale, setLocale } }
export { locale, setLocale }
