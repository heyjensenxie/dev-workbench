export type MessageKey = keyof typeof messages['en-US']

/** Exposed so tests can assert both locales stay in sync. */
export const messageCatalog = messages

/** Reads a preference without assuming a browser environment. */
function readStored(key: string): string | null {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage.getItem(key)
  } catch {
    return null
  }
}

function writeStored(key: string, value: string): void {
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(key, value)
  } catch {
    // Storage can be unavailable; preferences then only live for this session.
  }
}

function detectLocale(): Locale {
  const saved = readStored('locale')
  if (saved === 'zh-CN' || saved === 'en-US') return saved
  const language = typeof navigator === 'undefined' ? '' : navigator.language ?? ''
  return language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

const locale = ref<Locale>(detectLocale())
const languageLabel = computed(() => locale.value === 'zh-CN' ? 'EN' : '中')

export type MessageParams = Record<string, string | number>

function setLocale(next: Locale): void {
  locale.value = next
  writeStored('locale', next)
  if (typeof document !== 'undefined') document.documentElement.lang = next
}
function toggleLocale(): void {
  setLocale(locale.value === 'zh-CN' ? 'en-US' : 'zh-CN')
}

/** Replaces `{name}` placeholders, leaving unknown placeholders untouched. */
function interpolate(template: string, params?: MessageParams): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    name in params ? String(params[name]) : placeholder)
}

/** Translates a key with optional `{placeholder}` values. */
function t(key: MessageKey, params?: MessageParams): string {
  return interpolate(messages[locale.value][key], params)
}

if (typeof document !== 'undefined') document.documentElement.lang = locale.value

/**
 * Both the native runtime and the browser preview describe their own output with
 * locale-neutral codes. Anything else — a driver message, an engine error — is
 * returned unchanged so real diagnostics are never hidden by a missing key.
 */
const databaseMessageKeys: Record<string, MessageKey> = {
  [DATABASE_MESSAGE_CODES.connectedMysql]: 'dbMessageConnectedMysql',
  [DATABASE_MESSAGE_CODES.connectedSqlite]: 'dbMessageConnectedSqlite',
  [DATABASE_MESSAGE_CODES.statementExecuted]: 'dbMessageStatementExecuted',
  [DATABASE_MESSAGE_CODES.queryCancelled]: 'dbMsgQueryCancelled',
  [DATABASE_MESSAGE_CODES.limitReached]: 'dbMessageLimitReached',
  [DATABASE_MESSAGE_CODES.unknownHost]: 'dbMessageUnknownHost',
}

const warningTitleKeys: Record<SqlSafetyWarningKind, MessageKey> = {
  drop: 'dbWarningDropTitle',
  truncate: 'dbWarningTruncateTitle',
  alter: 'dbWarningAlterTitle',
  'update-without-where': 'dbWarningUpdateTitle',
  'delete-without-where': 'dbWarningDeleteTitle',
}

const warningDetailKeys: Record<SqlSafetyWarningKind, MessageKey> = {
  drop: 'dbWarningDropDetail',
  truncate: 'dbWarningTruncateDetail',
  alter: 'dbWarningAlterDetail',
  'update-without-where': 'dbWarningUpdateDetail',
  'delete-without-where': 'dbWarningDeleteDetail',
}

/** Localizes a database runtime message code, passing raw engine text through. */
export function translateDatabaseMessage(message: string | undefined): string | undefined {
  if (!message) return undefined
  const key = databaseMessageKeys[message]
  return key ? t(key) : message
}

/** Localizes a locale-neutral SQL safety finding reported by `packages/core`. */
export function translateSqlWarning(kind: SqlSafetyWarningKind): { title: string; detail: string } {
  return { title: t(warningTitleKeys[kind]), detail: t(warningDetailKeys[kind]) }
}

export function useI18n() { return { locale, languageLabel, t, toggleLocale, setLocale } }
